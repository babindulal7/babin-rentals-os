#!/usr/bin/env node
// Builds a dated staging SQL inventory snapshot (docs/verification/STAGING_SQL_INVENTORY_<date>.json).
//
// Source side: every supabase/migrations/*.sql at --source, read from Git (not the working tree),
// with its Git blob id and byte count. Live side: filenames compared with a committed ledger snapshot
// (docs/live/schema_migrations_<date>.txt). No database is contacted. Review states carry forward from
// the prior snapshot when the blob is unchanged; new files start as NEW_MIGRATION_REVIEW_REQUIRED.
//
//   node scripts/build-staging-inventory.mjs \
//     --prior STAGING_SQL_INVENTORY_2026-11-21.json \
//     --out STAGING_SQL_INVENTORY_2026-11-22.json \
//     --source HEAD --observed 2026-11-22 \
//     --ledger docs/live/schema_migrations_2026-11-20.txt
//
// Refuses to overwrite an existing snapshot. Exit 0 when the snapshot is written.

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const VERIFICATION = join(ROOT, 'docs', 'verification')

function argValue(name) {
  const index = process.argv.indexOf(name)
  if (index === -1 || !process.argv[index + 1]) throw new Error(`missing ${name}`)
  return process.argv[index + 1]
}

const priorName = argValue('--prior')
const outName = argValue('--out')
const source = argValue('--source')
const observed = argValue('--observed')
const ledgerPath = join(ROOT, argValue('--ledger'))

if (existsSync(join(VERIFICATION, outName))) throw new Error(`refusing to overwrite ${outName}`)

const prior = JSON.parse(readFileSync(join(VERIFICATION, priorName), 'utf8'))
const sourceCommit = execFileSync('git', ['rev-parse', source], { cwd: ROOT, encoding: 'utf8' }).trim()

const names = execFileSync('git', ['ls-tree', '--name-only', sourceCommit, 'supabase/migrations/'], { cwd: ROOT, encoding: 'utf8' })
  .split('\n')
  .filter((path) => path.endsWith('.sql'))
  .map((path) => path.replace('supabase/migrations/', ''))
  .sort()

const priorByName = new Map(prior.files.map((entry) => [entry.filename, entry]))

const ledgerRows = readFileSync(ledgerPath, 'utf8')
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith('#'))
  .map((line) => {
    const [version, ...rest] = line.split(/\s+/)
    return { version, name: rest.join(' ') }
  })
const liveNames = new Set(ledgerRows.map((row) => row.name))

const files = names.map((filename) => {
  const content = execFileSync('git', ['show', `${sourceCommit}:supabase/migrations/${filename}`], {
    cwd: ROOT,
    maxBuffer: 64 * 1024 * 1024,
  })
  const gitBlobSha = createHash('sha1').update(`blob ${content.length}\0`).update(content).digest('hex')
  const before = priorByName.get(filename)
  const reviewState = before
    ? before.git_blob_sha === gitBlobSha
      ? before.review_state
      : 'CHANGED_REVIEW_REQUIRED'
    : 'NEW_MIGRATION_REVIEW_REQUIRED'
  return {
    filename,
    git_blob_sha: gitBlobSha,
    bytes: content.length,
    live_exact_name_found: liveNames.has(filename.replace(/\.sql$/, '')),
    review_state: reviewState,
  }
})

const sourceNames = new Set(files.map((file) => file.filename.replace(/\.sql$/, '')))
const exact = files.filter((file) => file.live_exact_name_found).length

const added = names.filter((name) => !priorByName.has(name))
const removed = prior.files.map((entry) => entry.filename).filter((name) => !names.includes(name))
const changed = names.filter((name) => priorByName.has(name) && priorByName.get(name).git_blob_sha !== files.find((f) => f.filename === name).git_blob_sha)

const snapshot = {
  ...prior,
  title: `Staging SQL Inventory — ${observed} (re-pin of the 21 Nov snapshot)`,
  observed_date: observed,
  source_main_commit: sourceCommit,
  migration_files: files.length,
  live_recorded_history_count: ledgerRows.length,
  exact_name_matches: exact,
  source_without_exact_live_name: files.length - exact,
  live_without_exact_source_name: [...liveNames].filter((name) => !sourceNames.has(name)).length,
  current_live_ledger_rechecked: false,
  historical_live_comparison_observed_date: '2026-11-20',
  historical_live_comparison_source_commit: 'docs/live/schema_migrations_2026-11-20.txt',
  historical_comparison_note: `Counts compare source filenames against docs/live/schema_migrations_2026-11-20.txt (production ledger snapshot, 20 Nov). No live ledger read on ${observed}, no SQL equivalence, no dependency validation, no hosted apply authorization. Generated by scripts/build-staging-inventory.mjs. The 21 Nov snapshot records source_without_exact_live_name 109 where the same method gives 110 (148 + 110 = 258); that figure is not corrected here.`,
  source_drift_since_prior_snapshot: {
    prior_snapshot_date: prior.observed_date,
    prior_snapshot_commit: prior.source_main_commit,
    added_files: added,
    changed_files: changed,
    removed_files: removed,
  },
  files,
}

writeFileSync(join(VERIFICATION, outName), `${JSON.stringify(snapshot, null, 2)}\n`)
console.log(JSON.stringify({
  out: outName,
  source: sourceCommit,
  migration_files: files.length,
  exact_name_matches: exact,
  source_without_exact_live_name: files.length - exact,
  added_files: added,
  changed_files: changed,
  removed_files: removed,
}, null, 2))
